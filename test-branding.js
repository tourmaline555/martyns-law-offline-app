const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const file=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=file('index.html'), css=file('styles.css'), man=JSON.parse(file('manifest.webmanifest')), sw=file('sw.js'), app=file('app.js');
assert.match(html,/Premi<span class="brand-accent">vue<\/span>/);
assert.match(html,/Martyn's Law Readiness &amp; Assurance/);
assert.match(css,/--pv-navy:#10233b/);
assert.match(app,/Preparedness you can/);
assert.match(app,/About Premivue/);
assert.match(css,/--pv-mint:#64e0c9/);
assert.equal(man.short_name,'Premivue');
assert.match(sw,/ml-check-v40-audit-integrity/);
assert.match(sw,/favicon\.svg/);
assert.ok(fs.statSync(path.join(root,'assets/icon-192.png')).size>1000);
assert.ok(fs.statSync(path.join(root,'assets/icon-512.png')).size>2000);
const PDF=require('./pdf.js'), L=require('./logic.js'), vm=require('node:vm');
const q={};vm.runInNewContext(file('questions.js'),{window:q});
const b={...L.defaultState().business,name:'Sample Premises',site:'Example Site',date:'2026-11-14',activity:'shops',building:'yes',excluded:'no',peak:'250',events:'no',shared:'no'};
const answers=Object.fromEntries(L.activeQuestions(q.ASSESSMENT_QUESTIONS,b).map(q=>[q.id,'yes']));
answers.Q8='partly';
const s={business:b,answers,notes:{}};
const result=L.summarize(q.ASSESSMENT_QUESTIONS,b,answers);
const data=PDF.generate(s,result);
const str=Buffer.from(data).toString('latin1');
assert.match(str,/Premi/);
assert.match(str,/vue/);
assert.match(str,/MARTYN'S LAW READINESS & ASSURANCE/);
assert.equal((str.match(/\/Type \/Page \/Parent/g)||[]).length,3);
assert.ok(data.length>10000);
if(process.env.PREMIVUE_PDF_SAMPLE)fs.writeFileSync(process.env.PREMIVUE_PDF_SAMPLE,Buffer.from(data));
console.log('PASS v3.8: website-match logo, palette, PWA, cache and report header.');
