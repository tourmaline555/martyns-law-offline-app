const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const L=require('./logic.js');
const B=require('./basis.js');
const pdf=require('./pdf.js');
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync(__dirname+'/questions.js','utf8'),ctx);
const Q=ctx.window.ASSESSMENT_QUESTIONS;
const b={...L.defaultState().business,name:'Example Nightclub (fictional)',site:'Example Street, York',assessor:'Example assessor',date:'2026-11-14',
 activity:'entertainment',building:'no',excluded:'no',peak:'1000',peakMethod:'Entry count and staffing',
 events:'yes',eventLocation:'at_site',eventPeak:'1200',publicAccess:'yes',entryChecks:'no',eventExcluded:'no',accessGeneral:'yes',shared:'no',reviewDate:'2027-01-15'};
const active=L.activeQuestions(Q,b);assert.equal(active.length,37);
let answers=Object.fromEntries(active.map(q=>[q.id,'yes']));
for(const [id,v] of Object.entries({Q7:'not_sure',Q8:'partly',Q13:'no',Q15:'partly',Q25:'partly',Q26:'no',Q31:'no',Q32:'no',Q33:'no',Q34:'no'}))answers[id]=v;
let r=L.summarize(Q,b,answers);
assert.equal(Math.round(r.score),78);
assert.equal(r.rag,'Amber');
assert.match(r.scope.premises,/Review required - conflicting scope answers/);
assert.ok(r.scope.scopeUnknown);
assert.match(r.scope.reasons.join(' '),/club members/);
assert.equal(r.scope.event,'Not a qualifying event on stated information');
assert.equal(r.actions.length,10);
assert.equal(r.lowSections.includes('Documentation'),true);
assert.ok(r.answerChecks.some(s=>s.includes('Q5')&&s.includes('Q8')));
assert.ok(r.answerChecks.some(s=>s.includes('Q8')&&s.includes('Q11')));
assert.ok(r.answerChecks.some(s=>s.includes('Q17')&&s.includes('Q32')));
assert.ok(r.answerChecks.some(s=>s.includes('Q16')&&s.includes('Q26')));
for(const id of ['Q8','Q13','Q25','Q32','Q34'])assert.ok(r.actions.find(a=>a.q.id===id)?.action.length>85,id+' action is too generic');
assert.match(r.actions.find(a=>a.q.id==='Q8').action,/fire escape/);
const bytes=pdf.generate({business:b,answers,notes:{}},r);
assert.ok(bytes.length>5000);
const raw=Buffer.from(bytes).toString('latin1');
for(const s of ['Assessment summary','Legal scope - preliminary','SCOPE NEEDS REVIEW','DRAFT / NOT ARCHIVED','critical safeguards','Q8','Prioritised action plan'])assert.ok(raw.includes(s),s+' missing from PDF');
const out=process.env.SAMPLE_PDF||'(not written)';
if(process.env.SAMPLE_PDF)fs.writeFileSync(out,bytes);
assert.equal(L.computeScope({...b,building:'yes'}).premises,'Enhanced tier');
assert.match(L.computeScope({...b,excluded:'yes',building:'yes'}).premises,/Review required - claimed statutory exclusion/);
assert.equal(L.computeScope({...b,peak:'150'}).premises,'Not qualifying on stated information');
console.log('PASS v3.6: nightclub 78% Amber; scope conflict; 10 actions; Q5/Q8, Q8/Q11, Q16/Q26 and Q17/Q32 warnings; strong recommendations; enhanced-tier after corrected building access; PDF '+bytes.length+' bytes '+out);
