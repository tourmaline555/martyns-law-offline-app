const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
require('./basis.js');
const L=require('./logic.js');
const B=require('./basis.js');
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync(__dirname+'/questions.js','utf8'),ctx);
const Q=ctx.window.ASSESSMENT_QUESTIONS;
const base=L.defaultState().business;
const site=(overrides={})=>({...base,name:'Fictional Test Venue',site:'Example Street',building:'yes',activity:'hotel',excluded:'no',peak:'350',peakMethod:'Three years of busiest trading-day footfall and staff counts',events:'no',shared:'no',date:'2026-11-14',reviewDate:'2027-05-14',...overrides});
const result=(b,answer='yes')=>L.summarize(Q,b,Object.fromEntries(L.activeQuestions(Q,b).map(q=>[q.id,answer])));
assert.equal(Q.filter(q=>q.section!=='Scope').length,38);
const b=site();
assert.equal(L.computeScope(b).premises,'Standard tier');
assert.equal(result(b).rag,'Green');
assert.equal(result(b).score,100);
assert.equal(result(site({peak:'199'})).scope.premises,'Not qualifying on stated information');
assert.equal(result(site({peak:'800'})).scope.premises,'Enhanced tier');
for(const activity of ['worship','childcare','school','further']){
 const r=result(site({peak:'1200',activity,events:'yes',eventPeak:'1200',eventLocation:'at_site',publicAccess:'yes',entryChecks:'yes',eventExcluded:'no'}));
 assert.equal(r.scope.premises,'Standard tier');
 assert.equal(r.scope.event,'Not a qualifying event on stated information');
}
assert.equal(result(site({activity:'higher',peak:'1200'})).scope.premises,'Enhanced tier');
const ev=site({events:'yes',eventLocation:'at_site',eventPeak:'900',publicAccess:'yes',entryChecks:'yes',eventExcluded:'no'});
assert.equal(L.computeScope(ev).event,'Potential qualifying event (enhanced duties)');
assert.equal(L.computeScope({...ev,entryChecks:'no'}).event,'Not a qualifying event on stated information');
assert.equal(L.computeScope({...ev,publicAccess:'no'}).event,'Not a qualifying event on stated information');
assert.equal(L.computeScope({...ev,eventLocation:'separate'}).event,'Separate location - assess independently');
assert.match(L.computeScope({...ev,eventLocation:'both'}).event,/Review required/);
assert.match(L.computeScope({...ev,eventLocation:'unknown'}).event,/Review required/);
assert.match(L.computeScope({...ev,events:'unknown'}).event,/Review required/);
assert.equal(L.activeQuestions(Q,site({events:'no',shared:'no'})).length,33);
assert.equal(L.activeQuestions(Q,site({events:'unknown',shared:'unknown'})).length,38);
const answers={Q5:'partly',Q24:'no',Q25:'partly',Q31:'no',Q35:'partly',Q38:'no',Q41:'no'};
function summaries(b){const a=Object.fromEntries(L.activeQuestions(Q,b).map(q=>[q.id,'yes']));Object.assign(a,answers);return L.summarize(Q,b,a);}
const standard=summaries(site({shared:'yes',otherResponsible:'yes',events:'yes',eventLocation:'at_site',eventPeak:'350',publicAccess:'yes',entryChecks:'yes',eventExcluded:'no'}));
const enhanced=summaries(site({peak:'810',shared:'yes',otherResponsible:'yes',events:'yes',eventLocation:'at_site',eventPeak:'900',publicAccess:'yes',entryChecks:'yes',eventExcluded:'no'}));
const action=(r,id)=>r.actions.find(x=>x.q.id===id)?.action||'';
assert.match(action(standard,'Q31'),/not automatically required/);
assert.match(action(enhanced,'Q31'),/section 7 compliance document/);
assert.match(action(standard,'Q24'),/advisory/);
assert.match(action(enhanced,'Q24'),/section 6/);
assert.match(action(standard,'Q35'),/Standard tier/);
assert.match(action(enhanced,'Q35'),/section 10/);
assert.match(action(standard,'Q38'),/section 8/);
assert.match(action(standard,'Q41'),/Standard-tier/);
assert.match(action(enhanced,'Q41'),/Enhanced-tier/);
assert.equal(B.classify('Q31',standard.scope,site()).kind,'advisory');
assert.equal(B.classify('Q31',enhanced.scope,site()).kind,'linked');
assert.equal(B.classify('Q5',L.computeScope(site({peak:'100'})),site()).kind,'conditional');
const html=fs.readFileSync(__dirname+'/app.js','utf8');
for(const fld of ['peakMethod','eventLocation','otherResponsible','reviewDate']) assert.match(html,new RegExp(fld));
const pdf=require('./pdf.js');
const pdfBytes=pdf.generate({business:enhanced.scope?site({peak:'810',shared:'yes',otherResponsible:'yes',events:'yes',eventPeak:'900',eventLocation:'at_site',publicAccess:'yes',entryChecks:'yes',eventExcluded:'no'}):b,answers:{},notes:{}},enhanced);
assert.ok(pdfBytes.length>10000);
if(process.env.SAMPLE_PDF)fs.writeFileSync(process.env.SAMPLE_PDF,pdfBytes);
console.log('PASS: 12-field scope structure; premises thresholds; event exclusions and location routing; tier-specific recommendation texts; RAG unchanged; PDF '+pdfBytes.length+' bytes.');
