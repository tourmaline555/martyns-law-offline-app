'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const Q=require('./question-data.json'),Logic=require('./logic.js'),PDF=require('./pdf.js'),I=require('./integrity.js');
globalThis.PremivueIntegrity=I;
const fixture=JSON.parse(fs.readFileSync('./tests/fixtures/riverside-three.json','utf8'));
